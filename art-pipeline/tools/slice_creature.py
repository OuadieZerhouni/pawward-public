"""Turn a finished creature render into the layers the game animates. Fully automatic.

WHY THIS IS SMALL. The original plan sliced eight layers per creature by hand in Krita, about
20 minutes each, 20 times. Almost all of that was unnecessary: of the four idle motions, only
ONE needs geometry separated out.

    breathing   whole sprite, scale.y about its base    no layers needed
    sway        whole sprite, small rotation            no layers needed
    blink       a full-frame inpaint variant            no layers needed
    mouth       a full-frame inpaint variant            no layers needed
    pupils      must move independently                 <- the only real requirement

So the slice is: a body layer whose eyes are blank (generated by inpainting the pupils away),
plus the pupil discs cut from the original at the positions the pupil detector already finds.
Two layers, no hand work, and no seam risk anywhere.

Losing the head/body split costs independent head sway. Whole-sprite sway reads the same at the
amplitudes involved (0.01 rad) and removes a class of artefact, so it is a good trade.

    python slice_creature.py <species> --base BASE.png --blank BLANK_EYES.png --out-dir DIR
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, str(Path(__file__).parent))
from make_masks import find_pupils

# Pupil discs are cut a little larger than the detected blob so the sclera edge and any painted
# highlight travel with the pupil rather than staying behind.
PUPIL_CUT_SCALE = 1.35
FEATHER_PX = 3


def _alpha_from_backdrop(img: Image.Image) -> Image.Image:
    """Derive a cutout mask by treating the near-uniform dark backdrop as transparent.

    The prompt fixes a plain flat dark charcoal background specifically so this works without a
    segmentation model. Sampling the corners rather than assuming a colour keeps it honest if the
    backdrop shade drifts between renders.
    """
    rgb = np.asarray(img.convert("RGB"), dtype=np.float32)
    h, w = rgb.shape[:2]
    patch = 24
    corners = np.concatenate([
        rgb[:patch, :patch].reshape(-1, 3), rgb[:patch, -patch:].reshape(-1, 3),
        rgb[-patch:, :patch].reshape(-1, 3), rgb[-patch:, -patch:].reshape(-1, 3),
    ])
    bg = np.median(corners, axis=0)

    dist = np.linalg.norm(rgb - bg, axis=2)
    # Two thresholds with a ramp between: hard-cut the clear background, keep the soft painted
    # edge semi-transparent so the cutout does not get a hard crunchy outline.
    lo, hi = 26.0, 62.0
    alpha = np.clip((dist - lo) / (hi - lo), 0.0, 1.0)

    mask = Image.fromarray((alpha * 255).astype(np.uint8), mode="L")
    return mask.filter(ImageFilter.GaussianBlur(1.2))


def _disc(size: tuple[int, int], centre: tuple[float, float], radius: float) -> Image.Image:
    m = Image.new("L", size, 0)
    d = ImageDraw.Draw(m)
    d.ellipse([centre[0] - radius, centre[1] - radius,
               centre[0] + radius, centre[1] + radius], fill=255)
    return m.filter(ImageFilter.GaussianBlur(FEATHER_PX))


def slice_creature(species: str, base_path: Path, blank_path: Path | None,
                   out_dir: Path) -> dict:
    base = Image.open(base_path).convert("RGB")
    size = base.size
    left, right, pupil_r = find_pupils(base)
    cut_r = pupil_r * PUPIL_CUT_SCALE

    cutout_alpha = _alpha_from_backdrop(base)

    out_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    def save(name: str, im: Image.Image) -> None:
        p = out_dir / f"{name}.png"
        im.save(p)
        written[name] = p.name

    # Pupil layers: the disc cut from the ORIGINAL render, on a full-size transparent canvas so
    # it registers with the body without any offset bookkeeping.
    for name, centre in (("pupil_l", left), ("pupil_r", right)):
        disc = _disc(size, centre, cut_r)
        layer = Image.new("RGBA", size, (0, 0, 0, 0))
        layer.paste(base, (0, 0), disc)
        save(name, layer)

    # Body: the blank-eyed render if one was generated, else the original with the pupils left
    # in. Falling back keeps the pipeline runnable before the blank-eyes pass exists — the
    # creature simply has non-tracking eyes until it does.
    body_src = base
    if blank_path is not None and blank_path.exists():
        body_src = Image.open(blank_path).convert("RGB")
    body = body_src.convert("RGBA")
    body.putalpha(cutout_alpha)
    save("body", body)

    meta = {
        "species": species,
        "canvas": list(size),
        # Pupil home positions and travel radius, in canvas pixels. The game reads these rather
        # than guessing, so eye tracking is correct per creature instead of per species-family.
        "pupils": [[round(left[0], 1), round(left[1], 1)],
                   [round(right[0], 1), round(right[1], 1)]],
        "pupil_radius": round(pupil_r, 1),
        # Travel is a fraction of the pupil radius: enough to read as looking, small enough that
        # the pupil never leaves its sclera.
        "pupil_travel": round(pupil_r * 0.55, 1),
        "layers": written,
        "blank_eyes": blank_path is not None and blank_path.exists(),
    }
    (out_dir / "slice.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    # Debug composite: body + pupils shoved sideways, to prove the cut is clean and that no
    # pupil-shaped hole shows through when they move.
    dbg = Image.new("RGBA", size, (20, 22, 28, 255))
    dbg.alpha_composite(body)
    for name in ("pupil_l", "pupil_r"):
        layer = Image.open(out_dir / f"{name}.png").convert("RGBA")
        dbg.alpha_composite(layer, (int(pupil_r * 0.5), int(pupil_r * 0.35)))
    dbg.convert("RGB").save(out_dir / "_debug_slice.png")

    print(f"{species}: pupils L={left[0]:.0f},{left[1]:.0f} R={right[0]:.0f},{right[1]:.0f} "
          f"r={pupil_r:.0f} blank_eyes={meta['blank_eyes']}")
    return meta


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("species")
    ap.add_argument("--base", required=True, type=Path)
    ap.add_argument("--blank", type=Path, default=None)
    ap.add_argument("--out-dir", required=True, type=Path)
    args = ap.parse_args()
    slice_creature(args.species, args.base, args.blank, args.out_dir)


if __name__ == "__main__":
    main()
